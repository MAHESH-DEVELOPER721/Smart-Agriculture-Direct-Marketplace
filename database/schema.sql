-- PostgreSQL schema for the SQLAlchemy models in backend/app/models.
CREATE TYPE user_role AS ENUM ('farmer', 'consumer', 'admin');

CREATE TABLE users (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(100) NOT NULL,
	email VARCHAR(150) NOT NULL,
	password_hash VARCHAR(255) NOT NULL,
	role user_role NOT NULL,
	created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ix_users_email ON users (email);

CREATE TABLE products (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(150) NOT NULL,
	category VARCHAR(60) NOT NULL,
	price DOUBLE PRECISION NOT NULL,
	unit VARCHAR(40) DEFAULT 'kg',
	stock INTEGER DEFAULT 0,
	farm_name VARCHAR(150) NOT NULL,
	description VARCHAR(500) DEFAULT '',
	is_featured BOOLEAN DEFAULT FALSE,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE soil_reports (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INTEGER NOT NULL REFERENCES users (id),
	location VARCHAR(120) NOT NULL,
	moisture_pct DOUBLE PRECISION NOT NULL,
	ph DOUBLE PRECISION NOT NULL,
	nitrogen DOUBLE PRECISION NOT NULL,
	phosphorus DOUBLE PRECISION NOT NULL,
	potassium DOUBLE PRECISION NOT NULL,
	recommendation VARCHAR(500) DEFAULT '',
	created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE drought_alerts (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	region VARCHAR(120) NOT NULL,
	severity VARCHAR(40) NOT NULL,
	rainfall_mm DOUBLE PRECISION NOT NULL,
	soil_moisture_pct DOUBLE PRECISION NOT NULL,
	recommendation VARCHAR(500) DEFAULT '',
	created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE orders (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_code VARCHAR(40) UNIQUE NOT NULL,
	user_id INTEGER REFERENCES users (id),
	customer_name VARCHAR(120) NOT NULL,
	customer_email VARCHAR(150) NOT NULL,
	customer_phone VARCHAR(30) DEFAULT '',
	shipping_address VARCHAR(300) NOT NULL,
	total_amount DOUBLE PRECISION NOT NULL,
	status VARCHAR(40) DEFAULT 'confirmed',
	created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE order_items (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_id INTEGER NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
	product_id INTEGER REFERENCES products (id),
	product_name VARCHAR(150) NOT NULL,
	price DOUBLE PRECISION NOT NULL,
	quantity INTEGER NOT NULL DEFAULT 1,
	unit VARCHAR(40) DEFAULT 'kg'
);

